#!/usr/bin/env python3
"""Generate the level menu file from a game's world database.

Each line:  level_id|display name|entry1,entry2,...   (first entry = default)
Entries are the Name of party entry points (_Instance_Entry with template EntryPortalParty or
EntryPortal) - the identifiers LocationManager::ChangeLocation expects.

Usage: gen_levels.py [d1|rot|rot_a1|all] [--out DIR]
'all' (default) covers the games found through game_paths.py. Without --out the file goes to the
game folder.
The mod reads <game>/drakensang_mod_levels_<exe>.txt, falling back to drakensang_mod_levels.txt.
"""
import argparse
import os
import sqlite3
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from game_paths import D1_DIR, ROT_DIR  # noqa: E402

# name: (game dir, world db, locale dbs (later ones override), output file)
PRESETS = {
    'd1': (D1_DIR, 'game.db4', ['locale.db4'], 'drakensang_mod_levels.txt'),
    'rot': (ROT_DIR, 'game.db4', ['locale.db4'], 'drakensang_mod_levels_drakensang.txt'),
    'rot_a1': (ROT_DIR, 'gamea1.db4', ['locale.db4', 'localea1.db4'], 'drakensang_mod_levels_drakensanga1.txt'),
}

SKIP = {'_garbage_', '_graveyard_', '_nirvana_', 'worldmap', 'mainscreen_location', 'currentencounter'}
PREFERRED = ('von_karte', 'entry_start', '_start', 'start', 'fallback')
# level id -> (entry, "x y z yaw"): arrive at the entry, then the mod moves the party to the point
ARRIVAL = {
    'location08': ('loc08_entry_party_tempel', '-108 11 8 0'),     # Tallon: the square with the fountains
}


def decode(b):
    """Drakensang (2008) stores Windows-1252 text, The River of Time UTF-8."""
    try:
        return b.decode('utf-8')
    except UnicodeDecodeError:
        return b.decode('cp1252', 'replace')


def ro(path):
    db = sqlite3.connect('file:%s?mode=ro' % path, uri=True)
    db.text_factory = decode
    return db


def generate(gamedir, gamedb, localedbs, outname, outdir=None):
    db = os.path.join(gamedir, 'export', 'db')
    out = os.path.join(outdir or gamedir, outname)
    game = ro(os.path.join(db, gamedb))
    names = {}
    for l in localedbs:
        names.update(ro(os.path.join(db, l)).execute(
            "select LocaId, LocaText from _Locale where LocaId like 'name_%' and LocaText<>''"))

    def column(table, col):
        try:
            return {r[0] for r in game.execute('select "%s" from "%s"' % (col, table)) if r[0]}
        except sqlite3.OperationalError:
            return set()
    # where the game itself puts the party: arrival from the world map, then fallback entries of exits
    map_entries = column('_Instance_LocationButton', 'ExitEntryPoint')
    fallback_entries = column('_Instance_Exit', 'FallBackEntry')

    levels = game.execute('select Id, Name from _Instance_Levels order by Id').fetchall()
    rows = []
    for lid, nameKey in levels:
        if lid in SKIP:
            continue
        entries = [r[0] for r in game.execute(
            "select Name from _Instance_Entry where _Level=? and Id in ('EntryPortalParty','EntryPortal') "
            "and Name is not null and Name<>'' order by (Id<>'EntryPortalParty'), Name", (lid,))]
        seen = set()
        entries = [e for e in entries if not (e in seen or seen.add(e))]
        if not entries:
            continue
        # default: the world map arrival point, an exit's fallback entry, then a regular
        # (non-cutscene) entry, preferably the map/start/fallback one
        regular = [e for e in entries if 'cut' not in e.lower()] or entries
        default = next((e for e in regular if e in map_entries), None) or \
            next((e for e in regular if e in fallback_entries), None)
        for key in PREFERRED:
            if default:
                break
            default = next((e for e in regular if key in e.lower()), None)
        default = default or regular[0]
        arrival = ''
        if lid in ARRIVAL and ARRIVAL[lid][0] in entries:
            default, arrival = ARRIVAL[lid]
        if default:
            entries.remove(default)
            entries.insert(0, default)
        title = names.get(nameKey or '', '') or lid
        rows.append((lid, title.replace('|', '/'), entries, arrival))

    rows.sort(key=lambda r: (r[0].startswith('dungeon'), r[0].startswith('location_zufall'), r[1].lower()))
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('# Drakensang mod level menu: level_id|name|entry points (first = default)|arrival point\n')
        f.write('# arrival point (optional) "x y z yaw": after travelling via the default entry, the party\n')
        f.write('# is moved there (e.g. the centre of a town that has no entry point of its own)\n')
        f.write('# Generated by _mod/tools/gen_levels.py from export/db/%s\n' % gamedb)
        for lid, title, entries, arrival in rows:
            f.write('%s|%s|%s%s\n' % (lid, title, ','.join(entries), '|' + arrival if arrival else ''))
    print('wrote %d levels to %s' % (len(rows), out))


def main():
    ap = argparse.ArgumentParser(description='Generate the level menu files.')
    ap.add_argument('which', nargs='?', default='all', choices=list(PRESETS) + ['all'])
    ap.add_argument('--out', help='output directory (default: the game folder)')
    args = ap.parse_args()
    done = 0
    for name, (gamedir, gamedb, localedbs, outname) in PRESETS.items():
        if args.which in (name, 'all') and gamedir and os.path.exists(os.path.join(gamedir, 'export', 'db', gamedb)):
            generate(gamedir, gamedb, localedbs, outname, args.out)
            done += 1
    if not done:
        sys.exit('no game found: set DRAKENSANG_DIR and/or DRAKENSANG_ROT_DIR')


if __name__ == '__main__':
    sys.exit(main())
